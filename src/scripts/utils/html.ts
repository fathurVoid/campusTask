/**
 * Escapes user-provided text before it is injected via innerHTML.
 * This keeps the localStorage-driven UI safe from accidental HTML injection.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
